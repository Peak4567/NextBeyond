function scoreBadges(gpax, folio, interview, other) {
  const badges = [];
  if (gpax) badges.push({ key: "gpax", label: "GPAX", weight: gpax });
  if (folio) badges.push({ key: "portfolio", label: "แฟ้มสะสมผลงาน (Portfolio)", weight: folio });
  if (interview) badges.push({ key: "interview", label: "สัมภาษณ์", weight: interview });
  if (other) badges.push({ key: "other", label: "คะแนนอื่น", weight: other });
  return badges.sort((a, b) => b.weight - a.weight);
}

function gpaBreakdown(math, sci, lang, extra) {
  const req = [];
  if (math && math !== "-") req.push({ label: "หน่วยกิตคณิตศาสตร์", value: `${math} หน่วยกิต` });
  if (sci && sci !== "-") req.push({ label: "หน่วยกิตวิทยาศาสตร์", value: `${sci} หน่วยกิต` });
  if (lang && lang !== "-") req.push({ label: "หน่วยกิตภาษาต่างประเทศ", value: `${lang} หน่วยกิต` });
  if (extra) req.push({ label: "เกณฑ์เพิ่มเติม", value: extra });
  return req;
}

